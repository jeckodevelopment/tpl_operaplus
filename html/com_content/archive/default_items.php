defined('_JEXEC') or die;

use Joomla\CMS\HTML\HTMLHelper;
use Joomla\CMS\Layout\LayoutHelper;
use Joomla\CMS\Router\Route;
use Joomla\Component\Content\Site\Helper\RouteHelper;

/** @var \Joomla\Component\Content\Site\View\Archive\HtmlView $this */
$params = $this->params;
if (\Joomla\CMS\Factory::getApplication()->getTemplate(true)->params->get('presentationMode', 'standard') !== 'magazine') {
    require JPATH_SITE . '/components/com_content/tmpl/archive/default_items.php';
    return;
}
require_once __DIR__ . '/../../magazine/category-info.php';
require_once __DIR__ . '/../../seo.php';
$levels = \Joomla\CMS\Factory::getApplication()->getIdentity()->getAuthorisedViewLevels();

?>
<div id="archive-items" class="com-content-archive__items">
    <?php foreach ($this->items as $i => $item) : ?>
        <?php $info = $item->params->get('info_block_position', 0); ?>
        <?php
        $images = json_decode((string) ($item->images ?? '{}'));
        $image = in_array((int) ($item->access ?? 0), $levels, true)
            ? opSeoUrl($images->image_intro ?? '', \Joomla\CMS\Uri\Uri::root()) : '';
        ?>
        <div class="row<?php echo $i % 2; ?> op-mag-archive__item<?php echo $image !== '' ? ' op-mag-archive__item--image' : ''; ?>">
            <?php if ($image !== '') : ?>
                <div class="op-mag-archive__image"><?php echo LayoutHelper::render('joomla.content.intro_image', $item); ?></div>
            <?php endif; ?>
            <div class="op-mag-archive__copy">
            <div class="page-header">
                <h2>
                    <?php if ($params->get('link_titles')) : ?>
                        <a href="<?php echo Route::_(RouteHelper::getArticleRoute($item->slug, $item->catid, $item->language)); ?>" >
                            <?php echo $this->escape($item->title); ?>
                        </a>
                    <?php else : ?>
                        <?php echo $this->escape($item->title); ?>
                    <?php endif; ?>
                </h2>

                <?php // Content is generated by content plugin event "onContentAfterTitle" ?>
                <?php echo $item->event->afterDisplayTitle; ?>

            </div>
        <?php $useDefList = ($params->get('show_modify_date') || $params->get('show_publish_date') || $params->get('show_create_date')
            || $params->get('show_hits') || $params->get('show_category') || $params->get('show_parent_category')); ?>
        <?php if ($useDefList && ($info == 0 || $info == 2)) : ?>
            <?php echo opMagazineCategoryInfo($item, $params, 'above'); ?>
        <?php endif; ?>

        <?php // Content is generated by content plugin event "onContentBeforeDisplay" ?>
        <?php echo $item->event->beforeDisplayContent; ?>
        <?php if ($params->get('show_intro')) : ?>
            <div class="intro" > <?php echo HTMLHelper::_('string.truncateComplex', $item->introtext, $params->get('introtext_limit')); ?> </div>
        <?php endif; ?>

        <?php if ($useDefList && ($info == 1 || $info == 2)) : ?>
            <?php echo opMagazineCategoryInfo($item, $params, 'below'); ?>
        <?php endif; ?>
        <?php // Content is generated by content plugin event "onContentAfterDisplay" ?>
        <?php echo $item->event->afterDisplayContent; ?>
            </div>
        </div>
    <?php endforeach; ?>
</div>
<div class="com-content-archive__navigation w-100">
    <?php if ($this->params->def('show_pagination_results', 1)) : ?>
        <p class="com-content-archive__counter counter float-end pt-3 pe-2">
            <?php echo $this->pagination->getPagesCounter(); ?>
        </p>
    <?php endif; ?>
    <div class="com-content-archive__pagination">
        <?php echo $this->pagination->getPagesLinks(); ?>
    </div>
</div>
